"""
coordination.py
===============
Computes coordination number, coordination geometry classification, and
key inter-ligand angles for a metal ion in a protein structure.

Coordination Number
-------------------
The coordination number (CN) is the **number of donor atoms** bound to the
metal.  A bidentate carboxylate contributes two atoms (O1 and O2), so it
adds 2 to the CN.  Geometry is determined by the arrangement of donor atoms,
not residues, which is why atoms are counted.

There is ONE list of donor atoms per site, built by ``motif.py`` and passed
to this module.  It contains, depending on what was requested:

* protein donor atoms (side-chain O/N/S and backbone carbonyl O) of the
  protein chain the window belongs to;
* coordinated water oxygens (unless ``--no_water``);
* N/O/S atoms of non-protein ligands (unless ``--no_ligands``).

The CN, all L-M-L angles and the geometry are computed from this one list,
so they are always consistent with the listed donor atoms.  With
``--no_water --no_ligands`` the list contains the protein donor atoms only
and the CN is the number of those atoms.

Coordination Geometry (template fitting)
-----------------------------------------
The geometry is assigned by comparing the arrangement of the donor atoms with
a library of ideal polyhedra, not by threshold rules.

1.  Each donor is reduced to a unit vector from the metal.
2.  For every ideal polyhedron with the same number of vertices as there
    are donors, the observed unit vectors are fitted to the template vertices
    over all rotations and all one-to-one assignments of donors to vertices.
    The fit alternates an optimal assignment (Hungarian algorithm) with an
    optimal rotation (Kabsch), from 100 fixed starting rotations (a fixed
    seed, so results are reproducible).
3.  The RMSD of the best fit is reported in Angstrom: the root-mean-square
    displacement of the donor atoms, after moving each onto the sphere of
    radius equal to the mean metal-donor distance, from the best-fit ideal
    vertices.  It measures angular deviation only.
4.  The geometry with the lowest RMSD is the label.  The second-best
    template and its RMSD, and the margin between the two, are reported so
    that marginal assignments can be recognised.  No threshold is applied
    unless ``max_rmsd`` is given, in which case a best fit worse than
    ``max_rmsd`` is labelled "Irregular".

The templates (``ideal_polyhedra.py``, generated by
``tools/make_ideal_polyhedra.py``) are the ChemEnv reference geometries
(Waroquiers et al., 2017) for coordination numbers 2-9.  Sites with more than
9 donor atoms, or a single donor atom, are not fitted.  Only the geometries in
the library can be assigned; others will be assigned to the closest library
member, with a correspondingly large RMSD.

All L-M-L angles are computed; the mean, minimum, maximum and the two
largest are reported.

References
----------
Waroquiers, D. et al. (2017). Chem. Mater. 29, 8346-8360 (ChemEnv geometries).
Andreini, C. et al. (2012). Bioinformatics 28, 1658-1660 (FindGeo; the
template-comparison principle).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field

import numpy as np
from Bio.PDB.Residue import Residue
from scipy.optimize import linear_sum_assignment

from ideal_polyhedra import POLYHEDRA

log = logging.getLogger(__name__)

# ===========================================================================
# Data classes
# ===========================================================================

@dataclass
class DonorAtom:
    """One donor atom bound to the metal.

    Attributes
    ----------
    label : str
        Human-readable identifier, e.g. ``"ASP8:OD1"``, ``"HOH:W:101:O"``,
        ``"ATP:L:501:O2G"``.
    coord : np.ndarray
        Cartesian coordinates (Angstrom).
    source : str
        ``"protein"``, ``"water"`` or ``"ligand"`` (non-protein, non-water).
    """
    label: str
    coord: np.ndarray
    source: str
    # Atom identity, used to write the donor atoms to a PDB file (FindGeo input)
    resname: str = ""
    chain: str = ""
    resnum: str = ""        # residue number + insertion code
    atom_name: str = ""
    element: str = ""
    hetero: bool = False    # HETATM (water, ligand) rather than ATOM


@dataclass
class CoordinationResult:
    """Coordination analysis result for one metal ion site.

    Attributes
    ----------
    coordination_number : int
        Number of donor atoms in the list that was analysed (protein donors
        + coordinated waters + non-protein ligand atoms, as requested).
    mean_distance : float or None
        Mean metal-donor distance (A); the RMSD scale factor.
    cn_protein, cn_water, cn_ligand : int
        The three components of ``coordination_number``.
    geometry : str
        Best-fitting ideal polyhedron for ALL donor atoms ("Irregular" if a
        ``max_rmsd`` was given and exceeded).
    geometry_rmsd : float or None
        RMSD (A) of the best fit.
    geometry_second, geometry_second_rmsd, geometry_margin
        Second-best template, its RMSD, and the RMSD difference.
    geometry_protein_only, geometry_rmsd_protein_only
        Best fit using the protein donor atoms alone (shows the effect of
        including water / ligands).
    mean_angle, min_angle, max_angle : float
        L-M-L angle statistics over all donor atoms (degrees).
    angle_largest_1, angle_largest_2 : float
        Two largest L-M-L angles (degrees).
    donor_atoms : str
        Comma-separated labels of ALL donor atoms.
    all_angles : list[float]
        All pairwise L-M-L angles in degrees.
    """
    coordination_number: int = 0
    mean_distance: float | None = None   # mean metal-donor distance (A)
    min_distance: float | None = None    # shortest / longest metal-donor distance (A)
    max_distance: float | None = None
    cn_protein: int = 0
    cn_water: int = 0
    cn_ligand: int = 0
    geometry: str = "Unknown"
    geometry_rmsd: float | None = None
    geometry_second: str = ""
    geometry_second_rmsd: float | None = None
    geometry_margin: float | None = None
    geometry_protein_only: str = "Unknown"
    geometry_rmsd_protein_only: float | None = None
    mean_angle: float = 0.0
    min_angle: float = 0.0
    max_angle: float = 0.0
    angle_largest_1: float = 0.0
    angle_largest_2: float = 0.0
    donor_atoms: str = ""
    all_angles: list[float] = field(default_factory=list)


# ===========================================================================
# Angle computation
# ===========================================================================

def _lml_angles(donors: list[tuple[str, np.ndarray]],
                ion_pos: np.ndarray) -> list[float]:
    """Compute all pairwise L–M–L angles between donor atoms.

    Parameters
    ----------
    donors : list[tuple[str, np.ndarray]]
        Donor atoms (label, coordinate).
    ion_pos : np.ndarray
        Metal ion position.

    Returns
    -------
    list[float]
        Angles in degrees, one per unique pair.
    """
    angles: list[float] = []
    coords = [c for _, c in donors]
    n = len(coords)

    for i in range(n):
        for j in range(i + 1, n):
            v1 = coords[i] - ion_pos
            v2 = coords[j] - ion_pos
            n1 = np.linalg.norm(v1)
            n2 = np.linalg.norm(v2)
            if n1 < 1e-6 or n2 < 1e-6:
                continue
            cos_angle = np.clip(np.dot(v1, v2) / (n1 * n2), -1.0, 1.0)
            angle = float(np.degrees(np.arccos(cos_angle)))
            angles.append(angle)

    return sorted(angles, reverse=True)


# ===========================================================================
# Geometry: template fitting
# ===========================================================================

_N_STARTS = 100          # starting rotations per fit
_START_SEED = 20240601   # fixed seed -> reproducible results


def _rotations_from_quaternions(q: np.ndarray) -> np.ndarray:
    q = q / np.linalg.norm(q, axis=1)[:, None]
    w, x, y, z = q.T
    R = np.empty((len(q), 3, 3))
    R[:, 0, 0] = 1 - 2 * (y * y + z * z)
    R[:, 0, 1] = 2 * (x * y - z * w)
    R[:, 0, 2] = 2 * (x * z + y * w)
    R[:, 1, 0] = 2 * (x * y + z * w)
    R[:, 1, 1] = 1 - 2 * (x * x + z * z)
    R[:, 1, 2] = 2 * (y * z - x * w)
    R[:, 2, 0] = 2 * (x * z - y * w)
    R[:, 2, 1] = 2 * (y * z + x * w)
    R[:, 2, 2] = 1 - 2 * (x * x + y * y)
    return R


_START_ROTATIONS = _rotations_from_quaternions(
    np.random.default_rng(_START_SEED).normal(size=(_N_STARTS, 4))
)
_START_ROTATIONS[0] = np.eye(3)


def _fit_unit_rmsd(obs: np.ndarray, tmpl: np.ndarray) -> float:
    """Minimum RMSD (unit-sphere) between observed and template unit vectors.

    Minimised over rotations and one-to-one assignments by alternating the
    optimal assignment (Hungarian) with the optimal rotation (Kabsch), from
    ``_N_STARTS`` fixed starting rotations.
    """
    n = len(obs)
    best = np.inf
    for R in _START_ROTATIONS:
        prev = np.inf
        tot = np.inf
        for _ in range(60):
            rot = tmpl @ R.T
            cost = ((obs[:, None, :] - rot[None, :, :]) ** 2).sum(axis=-1)
            rows, cols = linear_sum_assignment(cost)
            tot = float(cost[rows, cols].sum())
            if prev - tot < 1e-12:
                break
            prev = tot
            U, _, Vt = np.linalg.svd(tmpl[cols].T @ obs[rows])
            d = 1.0 if np.linalg.det(Vt.T @ U.T) >= 0 else -1.0
            R = Vt.T @ np.diag([1.0, 1.0, d]) @ U.T
        best = min(best, tot)
        if best < 1e-14:
            break
    return float(np.sqrt(best / n))


@dataclass
class GeometryFit:
    """Outcome of fitting the donor arrangement to the ideal polyhedra."""
    label: str
    rmsd: float | None = None          # A (see module docstring)
    second: str = ""
    second_rmsd: float | None = None
    margin: float | None = None        # second_rmsd - rmsd (A)


def classify_geometry(
    unit_vectors: np.ndarray,
    mean_distance: float,
    max_rmsd: float | None = None,
) -> GeometryFit:
    """Fit donor unit vectors to the ideal polyhedra of the same size.

    Parameters
    ----------
    unit_vectors : np.ndarray
        (N, 3) unit vectors from the metal to the N donor atoms.
    mean_distance : float
        Mean metal-donor distance (A), used to express the RMSD in Angstrom.
    max_rmsd : float, optional
        If given, a best fit with RMSD above this value (A) is labelled
        "Irregular".  By default no threshold is applied.
    """
    cn = len(unit_vectors)
    if cn == 0:
        return GeometryFit("No donor atoms within cutoff")
    if cn == 1:
        return GeometryFit("Monocoordinate")
    templates = POLYHEDRA.get(cn)
    if not templates:
        return GeometryFit(f"{cn}-coordinate (no template)")

    fits = sorted(
        (_fit_unit_rmsd(unit_vectors, np.asarray(v, dtype=float)) * mean_distance, name)
        for name, _symbol, v in templates
    )
    best_rmsd, best_name = fits[0]
    label = best_name
    if max_rmsd is not None and best_rmsd > max_rmsd:
        label = "Irregular"
    if len(fits) > 1:
        second_rmsd, second = fits[1]
        return GeometryFit(label, round(best_rmsd, 3), second,
                           round(second_rmsd, 3), round(second_rmsd - best_rmsd, 3))
    return GeometryFit(label, round(best_rmsd, 3))


def _unit_vectors(donors: list["DonorAtom"], ion_pos: np.ndarray) -> tuple[np.ndarray, float]:
    vecs = np.array([np.asarray(d.coord, dtype=float) - ion_pos for d in donors])
    dist = np.linalg.norm(vecs, axis=1)
    keep = dist > 1e-6
    return vecs[keep] / dist[keep][:, None], float(dist[keep].mean()) if keep.any() else 0.0


def _distance_range(donors: list["DonorAtom"], ion_pos: np.ndarray) -> tuple[float, float]:
    d = [float(np.linalg.norm(np.asarray(x.coord, dtype=float) - ion_pos)) for x in donors]
    return round(min(d), 2), round(max(d), 2)


# ===========================================================================
# Main entry point
# ===========================================================================

def analyse_coordination(
    donors: list[DonorAtom],
    ion: Residue,
    max_rmsd: float | None = None,
) -> CoordinationResult:
    """Compute the coordination analysis for one metal site.

    Parameters
    ----------
    donors : list[DonorAtom]
        ALL donor atoms of the site (protein, water, non-protein ligand), as
        assembled by ``motif.py``.  Their number is the coordination number.
    ion : Residue
        Metal ion HETATM residue (centroid used for multi-atom ions).
    max_rmsd : float, optional
        Label best fits with an RMSD (A) above this value "Irregular".  No
        threshold is applied by default.

    Returns
    -------
    CoordinationResult
    """
    ion_coords = [a.get_vector().get_array() for a in ion.get_atoms()]
    if not ion_coords:
        log.debug("Ion %s has no atoms - cannot compute coordination", ion.id)
        return CoordinationResult()
    ion_pos = np.mean(ion_coords, axis=0)

    cn = len(donors)
    protein = [d for d in donors if d.source == "protein"]
    result = CoordinationResult(
        coordination_number=cn,
        cn_protein=len(protein),
        cn_water=sum(1 for d in donors if d.source == "water"),
        cn_ligand=sum(1 for d in donors if d.source == "ligand"),
        donor_atoms=",".join(d.label for d in donors),
    )
    if cn == 0:
        result.geometry = result.geometry_protein_only = "No donor atoms within cutoff"
        return result

    pairs = [(d.label, np.asarray(d.coord, dtype=float)) for d in donors]
    angles = _lml_angles(pairs, ion_pos)

    unit, mean_dist = _unit_vectors(donors, ion_pos)
    result.mean_distance = round(mean_dist, 3)
    result.min_distance, result.max_distance = _distance_range(donors, ion_pos)
    fit = classify_geometry(unit, mean_dist, max_rmsd)
    result.geometry = fit.label
    result.geometry_rmsd = fit.rmsd
    result.geometry_second = fit.second
    result.geometry_second_rmsd = fit.second_rmsd
    result.geometry_margin = fit.margin

    # Geometry from the protein donors alone, for comparison
    if len(protein) == cn:
        result.geometry_protein_only = fit.label
        result.geometry_rmsd_protein_only = fit.rmsd
    elif protein:
        p_unit, p_mean = _unit_vectors(protein, ion_pos)
        p_fit = classify_geometry(p_unit, p_mean, max_rmsd)
        result.geometry_protein_only = p_fit.label
        result.geometry_rmsd_protein_only = p_fit.rmsd
    else:
        result.geometry_protein_only = "No protein donor atoms"

    if angles:
        result.mean_angle = round(float(np.mean(angles)), 2)
        result.min_angle = round(float(np.min(angles)), 2)
        result.max_angle = round(float(np.max(angles)), 2)
        result.angle_largest_1 = round(angles[0], 2)
        result.angle_largest_2 = round(angles[1], 2) if len(angles) > 1 else 0.0
    result.all_angles = [round(a, 2) for a in angles]

    log.debug(
        "Ion %s: CN=%d (protein %d, water %d, ligand %d), geometry=%s (RMSD %s), donors=%s",
        ion.get_resname(), cn, result.cn_protein, result.cn_water,
        result.cn_ligand, result.geometry, result.geometry_rmsd, result.donor_atoms,
    )
    return result
